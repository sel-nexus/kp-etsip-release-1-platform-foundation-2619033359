import { test, expect } from '@playwright/test';

test('administrator deletes a newly created application and its absence persists', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const name = `E2E delete application ${Date.now()}-${Math.random().toString(36).slice(2)}`;
  await page.goto('/login');
  await page.getByLabel('Email').fill(process.env.E2E_ADMIN_EMAIL ?? 'admin@ketsip.local');
  await page.getByLabel('Password').fill(process.env.E2E_ADMIN_PASSWORD ?? 'LocalAdmin123!');
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByRole('link', { name: 'Applications' }).click();
  await page.getByRole('button', { name: 'Create application' }).click();
  await page.getByLabel('Name', { exact: true }).fill(name);
  await page.getByLabel('Description').fill('Disposable administrator deletion test');
  const created = page.waitForResponse(response => new URL(response.url()).pathname === '/api/applications' && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Save application' }).click();
  const createResponse = await created;
  expect(createResponse.status()).toBe(201);
  const application = await createResponse.json();
  expect(application.name).toBe(name);
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible();
  const token = await page.evaluate(() => sessionStorage.getItem('kp-etsip-token'));
  expect(token).toBeTruthy();
  const headers = { Authorization: `Bearer ${token}` };
  const before = await page.request.get(`/api/applications/${application.id}`, { headers });
  expect(before.status()).toBe(200);
  expect((await before.json()).description).toBe('Disposable administrator deletion test');
  page.once('dialog', dialog => dialog.accept());
  const deleted = page.waitForResponse(response => new URL(response.url()).pathname === `/api/applications/${application.id}` && response.request().method() === 'DELETE');
  await page.getByRole('button', { name: 'Delete application' }).click();
  expect((await deleted).status()).toBe(204);
  await expect(page).toHaveURL(/\/applications$/);
  await page.getByLabel('Search').fill(name);
  await expect(page.getByRole('region', { name: 'Application results' })).toContainText('No applications match these filters.');
  await page.reload();
  await expect(page.getByRole('region', { name: 'Application results' })).toContainText('No applications match these filters.');
  await expect(page.getByRole('link', { name, exact: true })).toHaveCount(0);
  const after = await page.request.get(`/api/applications/${application.id}`, { headers });
  expect(after.status()).toBe(404);
  const filtered = await page.request.get('/api/applications', { headers, params: { search: name } });
  expect(filtered.status()).toBe(200);
  expect((await filtered.json()).total).toBe(0);
  expect(errors).toEqual([]);
});
