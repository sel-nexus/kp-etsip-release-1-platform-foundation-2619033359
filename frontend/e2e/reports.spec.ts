import { test, expect } from '@playwright/test';

test('auditor views inventory reports and filtered audit activity, and exports CSV', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto('/login');
  await page.getByLabel('Email').fill(process.env.E2E_AUDITOR_EMAIL ?? 'auditor@ketsip.local');
  await page.getByLabel('Password').fill(process.env.E2E_DEMO_PASSWORD ?? 'LocalDemo123!');
  await page.getByRole('button', { name: 'Sign in' }).click();
  await expect(page.getByRole('link', { name: 'Reports' })).toBeVisible();
  expect(await page.getByRole('link', { name: 'Administration' }).count()).toBe(0);
  const reportResponse = page.waitForResponse(response => response.url().includes('/api/reports/applications') && response.status() === 200);
  await page.getByRole('link', { name: 'Reports' }).click();
  const report = await (await reportResponse).json();
  await expect(page.getByRole('region', { name: 'Report results' })).toContainText(`${report.total} results`);
  const filteredReportResponse = page.waitForResponse(response => new URL(response.url()).pathname === '/api/reports/applications' && new URL(response.url()).searchParams.get('search') === 'Payment Gateway');
  await page.getByLabel('Search').fill('Payment Gateway');
  const filteredReportResult = await filteredReportResponse;
  expect(filteredReportResult.status()).toBe(200);
  const filteredReport = await filteredReportResult.json();
  const application = filteredReport.items.find((item: { name: string }) => item.name === 'Payment Gateway');
  expect(application).toBeDefined();
  await expect(page.getByRole('region', { name: 'Report results' }).getByRole('link', { name: application.name, exact: true })).toBeVisible();
  const applicationCsvResponse = page.waitForResponse(response => response.url().includes('/api/reports/applications') && response.url().includes('format=csv'));
  const applicationDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV' }).click();
  const csvResponse = await applicationCsvResponse;
  expect(csvResponse.status()).toBe(200);
  expect(csvResponse.headers()['content-type']).toContain('text/csv');
  const csvDownload = await applicationDownload;
  expect(csvDownload.suggestedFilename()).toBe('applications-report.csv');
  const csvStream = await csvDownload.createReadStream();
  const csvChunks: Buffer[] = [];
  for await (const chunk of csvStream) csvChunks.push(Buffer.from(chunk));
  const csv = Buffer.concat(csvChunks).toString('utf8');
  expect(csv).toContain('id,name,portfolioId');
  expect(csv).toContain(application.id);
  expect(csv).toContain(application.name);

  const detailResponse = page.waitForResponse(response => new URL(response.url()).pathname === `/api/applications/${application.id}` && response.request().method() === 'GET');
  await page.getByRole('region', { name: 'Report results' }).getByRole('link', { name: application.name, exact: true }).click();
  const detailResult = await detailResponse;
  expect(detailResult.status()).toBe(200);
  const detail = await detailResult.json();
  expect(detail.id).toBe(application.id);
  expect(detail.name).toBe(application.name);
  await expect(page).toHaveURL(new RegExp(`/applications/${application.id}$`));
  await expect(page.getByRole('heading', { name: detail.name, exact: true })).toBeVisible();
  await expect(page.getByText(detail.description, { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Reports' }).click();
  await expect(page.getByRole('region', { name: 'Report results' })).toBeVisible();
  const portfolioResponse = page.waitForResponse(response => response.url().includes('/api/reports/portfolios') && response.status() === 200);
  await page.getByLabel('Report').selectOption('portfolios');
  const portfolios = await (await portfolioResponse).json();
  await expect(page.getByRole('region', { name: 'Report results' })).toContainText(`${portfolios.total} results`);
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV' }).click();
  expect((await download).suggestedFilename()).toBe('portfolios-report.csv');
  const portfolio = portfolios.items.find((item: { applicationCount: number }) => item.applicationCount > 0);
  expect(portfolio).toBeDefined();
  const portfolioDetailResponse = page.waitForResponse(response => new URL(response.url()).pathname === `/api/portfolios/${portfolio.id}` && response.request().method() === 'GET');
  const portfolioApplicationsResponse = page.waitForResponse(response => new URL(response.url()).pathname === `/api/portfolios/${portfolio.id}/applications` && response.request().method() === 'GET');
  await page.getByRole('region', { name: 'Report results' }).getByRole('link', { name: portfolio.name, exact: true }).click();
  const portfolioDetailResult = await portfolioDetailResponse;
  const portfolioApplicationsResult = await portfolioApplicationsResponse;
  expect(portfolioDetailResult.status()).toBe(200);
  expect(portfolioApplicationsResult.status()).toBe(200);
  const portfolioDetail = await portfolioDetailResult.json();
  const portfolioApplications = await portfolioApplicationsResult.json();
  expect(portfolioDetail.id).toBe(portfolio.id);
  expect(portfolioDetail.name).toBe(portfolio.name);
  expect(portfolioApplications.items.length).toBeGreaterThan(0);
  await expect(page).toHaveURL(new RegExp(`/portfolios/${portfolio.id}$`));
  await expect(page.getByRole('heading', { name: portfolioDetail.name, exact: true })).toBeVisible();
  await expect(page.locator('dd').filter({ hasText: portfolioDetail.owner || 'Not specified' }).first()).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Applications', exact: true })).toBeVisible();
  for (const linked of portfolioApplications.items) {
    const link = page.getByRole('link', { name: linked.name, exact: true });
    await expect(link).toBeVisible();
    await expect(link).toHaveAttribute('href', `/applications/${linked.id}`);
  }
  const auditResponse = page.waitForResponse(response => response.url().includes('/api/audit-logs') && response.status() === 200);
  await page.getByRole('link', { name: 'Audit log' }).click();
  const audit = await (await auditResponse).json();
  await expect(page.getByRole('region', { name: 'Audit results' })).toContainText(`${audit.total} events`);
  const filteredResponse = page.waitForResponse(response => response.url().includes('action=export') && response.url().includes('/api/audit-logs') && response.status() === 200);
  await page.getByLabel('Action').fill('export');
  const filtered = await (await filteredResponse).json();
  expect(filtered.items.every((item: { action: string }) => item.action === 'export')).toBe(true);
  await expect(page.getByRole('region', { name: 'Audit results' })).toContainText(`${filtered.total} events`);
  expect(errors).toEqual([]);
});

test('auditor independently opens an application from the repository and exports its filtered CSV', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto('/login');
  await page.getByLabel('Email').fill(process.env.E2E_AUDITOR_EMAIL ?? 'auditor@ketsip.local');
  await page.getByLabel('Password').fill(process.env.E2E_DEMO_PASSWORD ?? 'LocalDemo123!');
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByRole('link', { name: 'Reports' }).click();
  await expect(page.getByRole('heading', { name: 'Reports', exact: true })).toBeVisible();
  const listResponse = page.waitForResponse(response => new URL(response.url()).pathname === '/api/applications' && response.request().method() === 'GET');
  await page.getByRole('link', { name: 'Applications' }).click();
  const listResult = await listResponse;
  expect(listResult.status()).toBe(200);
  const list = await listResult.json();
  await expect(page.getByRole('region', { name: 'Application results' })).toContainText(`${list.total} applications`);
  const filteredListResponse = page.waitForResponse(response => new URL(response.url()).pathname === '/api/applications' && new URL(response.url()).searchParams.get('search') === 'Payment Gateway');
  await page.getByLabel('Search').fill('Payment Gateway');
  const filteredListResult = await filteredListResponse;
  expect(filteredListResult.status()).toBe(200);
  const filteredList = await filteredListResult.json();
  const application = filteredList.items.find((item: { name: string }) => item.name === 'Payment Gateway');
  expect(application).toBeDefined();
  await expect(page.getByRole('region', { name: 'Application results' }).getByRole('link', { name: application.name, exact: true })).toBeVisible();
  const exportResponse = page.waitForResponse(response => new URL(response.url()).pathname === '/api/applications/export');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV' }).click();
  const exported = await exportResponse;
  expect(exported.status()).toBe(200);
  expect(new URL(exported.url()).searchParams.get('search')).toBe(application.name);
  expect(exported.headers()['content-type']).toContain('text/csv');
  const file = await download;
  expect(file.suggestedFilename()).toBe('applications.csv');
  const stream = await file.createReadStream();
  const chunks: Buffer[] = [];
  for await (const chunk of stream) chunks.push(Buffer.from(chunk));
  const csv = Buffer.concat(chunks).toString('utf8');
  expect(csv).toContain('name,portfolioId,criticality');
  expect(csv).toContain(application.name);
  expect(csv).toContain(application.portfolioId);
  expect(csv).not.toContain('Settlement Hub');
  const detailResponse = page.waitForResponse(response => new URL(response.url()).pathname === `/api/applications/${application.id}` && response.request().method() === 'GET');
  await page.getByRole('region', { name: 'Application results' }).getByRole('link', { name: application.name, exact: true }).click();
  const detailResult = await detailResponse;
  expect(detailResult.status()).toBe(200);
  const detail = await detailResult.json();
  expect(detail.id).toBe(application.id);
  await expect(page.getByRole('heading', { name: detail.name, exact: true })).toBeVisible();
  await expect(page.getByText(detail.description, { exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
